#!/usr/bin/env bash
# Regenerates clients/{kotlin,typescript,python} from contracts/api/openapi.yaml, then compiles each.
#   clients/generate.sh            regenerate + compile-check
#   clients/generate.sh --no-compile
# Never hand-edit the generated directories; change this script, normalize_spec.py or README.md.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

REDOCLY="@redocly/cli@2.77.0"
GEN="@openapitools/openapi-generator-cli@2.42.2"   # runs generator jar 7.27.0 (clients/openapitools.json)
TSC="typescript@5.9.3"

# 1. bundle (same inputs as contracts/api/check.sh), then normalise
mkdir -p "$work/contracts/api" "$work/contracts/sync"
cp "$root/contracts/api/openapi.yaml" "$root/contracts/api/redocly.yaml" "$work/contracts/api/"
cp -R "$root/contracts/sync/." "$work/contracts/sync/"
(cd "$work/contracts/api" && npx --yes "$REDOCLY" bundle openapi.yaml --config redocly.yaml -o "$work/bundle.json" >/dev/null)
python3 "$here/normalize_spec.py" "$work/bundle.json" "$work/spec.json"

# 2. generate
gen() { # generator, out dir, additional properties
  rm -rf "$here/$2"
  (cd "$here" && npx --yes "$GEN" generate -i "$work/spec.json" -g "$1" -o "$here/$2" \
    --additional-properties="$3" --skip-validate-spec >"$work/gen-$2.log" 2>&1) || { cat "$work/gen-$2.log" >&2; exit 1; }
}
gen kotlin kotlin "library=jvm-ktor,serializationLibrary=gson,enumPropertyNaming=UPPERCASE,packageName=app.kotobaya.client"
gen typescript-fetch typescript "npmName=@kotobaya/api-client,supportsES6=true,typescriptThreePlus=true"
gen python python "packageName=kotobaya_client,library=urllib3"
# drop non-deterministic / unused scaffolding
rm -f "$here"/python/git_push.sh "$here"/kotlin/gradlew "$here"/kotlin/gradlew.bat
rm -rf "$here"/kotlin/gradle
for d in kotlin typescript python; do
  printf '%s\n' "Generated by clients/generate.sh. Do not edit; see clients/README.md." > "$here/$d/GENERATED.txt"
done

[ "${1:-}" = "--no-compile" ] && exit 0

# 3. compile checks, in a scratch copy so no build output lands in the repo
echo "== typescript: tsc --noEmit"
cp -R "$here/typescript" "$work/ts"
(cd "$work/ts" && cat tsconfig.json >/dev/null && npx --yes -p "$TSC" tsc --noEmit --strict --skipLibCheck --target es2020 --moduleResolution node --module esnext --lib es2020,dom src/index.ts)
echo "== python: compileall + import"
python3 -m compileall -q "$here/python/kotobaya_client" >/dev/null
(cd "$here/python" && uv run --no-project --with-requirements requirements.txt python -I -c "import sys; sys.path.insert(0, '.'); import kotobaya_client, kotobaya_client.models, kotobaya_client.api")
echo "== kotlin: gradle compileKotlin"
cp -R "$here/kotlin" "$work/kt"
(cd "$work/kt" && gradle --no-daemon -q compileKotlin)
echo "clients: OK"
