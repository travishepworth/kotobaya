#!/usr/bin/env node
// Token generator (UI-DS): design/tokens/tokens.json → web CSS, the card stylesheet's token block, the
// styleguide's token table and the Compose theme. `node design/tokens/generate.mjs` writes the outputs;
// `--check` writes nothing and exits 1 when any output differs from what the JSON generates (drift).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { camel, contrastReport, fluid, fmt, parseHex, resolveColors } from './lib.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const ROOT = join(HERE, '..', '..');

export const OUT = {
	webCss: 'web/src/lib/tokens.css',
	webTs: 'web/src/lib/ui/tokens.generated.ts',
	cardCss: 'assets/card/card.css',
	compose: 'android/src/main/kotlin/kotobaya/android/ui/theme/Tokens.kt'
};

export const CARD_START = '/* @generated tokens:start (design/tokens/tokens.json; `make tokens`) */';
export const CARD_END = '/* @generated tokens:end */';

const BANNER = 'GENERATED by design/tokens/generate.mjs from design/tokens/tokens.json. Do not edit; run `make tokens`.';

/** @param {string} p */
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

/** @returns {any} */
export function loadTokens() {
	return JSON.parse(read('design/tokens/tokens.json'));
}

/** @param {string[]} stack */
const fontStack = (stack) => stack.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(', ');

/** @param {number} px */
const rem = (px) => (px === 0 ? '0' : `${fmt(px / 16)}rem`);

/** @param {number[]} b */
const bezier = (b) => `cubic-bezier(${b.map(fmt).join(', ')})`;

/** CSS blocks for one theme's colours. @param {Record<string,string>} colors @param {any} tokens @param {'light'|'dark'} theme @param {string} indent */
function colorDecls(colors, tokens, theme, indent) {
	const lines = Object.entries(colors).map(([k, v]) => `${indent}--kb-color-${k}: ${v.toLowerCase()};`);
	for (const [k, e] of Object.entries(tokens.elevation)) lines.push(`${indent}--kb-elevation-${k}: ${e[theme]};`);
	lines.push(`${indent}color-scheme: ${theme};`);
	return lines.join('\n');
}

/** @param {any} tokens */
export function webCss(tokens) {
	const colors = resolveColors(tokens);
	const t = tokens.type;
	const out = [];
	out.push(`/*\n * ${BANNER}\n *\n * Kotobaya design tokens (docs/DESIGN.md). Light by default; dark follows the OS unless an ancestor sets\n * data-theme="light|dark" (the manual override sets it on <html>). Any element may carry data-theme, so a\n * subtree can show the other theme (the styleguide does).\n * Breakpoints (min-width, px): ${Object.entries(tokens.breakpoint).map(([k, v]) => `${k} ${v}`).join(', ')}.\n */`);
	out.push(`:root,\n[data-theme='light'] {\n${colorDecls(colors.light, tokens, 'light', '\t')}\n}`);
	out.push(`@media (prefers-color-scheme: dark) {\n\t:root:not([data-theme='light']) {\n${colorDecls(colors.dark, tokens, 'dark', '\t\t')}\n\t}\n}`);
	out.push(`[data-theme='dark'] {\n${colorDecls(colors.dark, tokens, 'dark', '\t')}\n}`);

	const d = [];
	d.push(`\t--kb-family-sans: ${fontStack(tokens.font.sans)};`);
	d.push(`\t--kb-family-serif: ${fontStack(tokens.font.serif)};`);
	d.push(`\t--kb-family-mono: ${fontStack(tokens.font.mono)};`);
	for (const [role, r] of Object.entries(t.roles)) {
		d.push(`\t--kb-type-${role}-size: ${fluid(r.min, r.max, t.fluidFromPx, t.fluidToPx)};`);
		d.push(`\t--kb-type-${role}-lh: ${fmt(r.lh)};`);
		d.push(`\t--kb-type-${role}-weight: ${r.weight};`);
		d.push(`\t--kb-type-${role}-tracking: ${fmt(r.tracking)}em;`);
		d.push(`\t--kb-type-${role}: ${r.weight} var(--kb-type-${role}-size) / ${fmt(r.lh)} var(--kb-family-${r.family});`);
	}
	d.push(`\t--kb-ruby-scale: ${fmt(t.ruby.scale)};`);
	d.push(`\t--kb-ruby-min: ${fmt(t.ruby.minRem)}rem;`);
	d.push(`\t--kb-ruby-lh: ${fmt(t.ruby.lineHeight)};`);
	for (const [k, v] of Object.entries(tokens.space).sort((a, b) => a[1] - b[1])) d.push(`\t--kb-space-${k}: ${rem(v)};`);
	for (const [k, v] of Object.entries(tokens.radius)) d.push(`\t--kb-radius-${k}: ${v}px;`);
	for (const [k, v] of Object.entries(tokens.motion.duration)) d.push(`\t--kb-duration-${k}: ${v}ms;`);
	for (const [k, v] of Object.entries(tokens.motion.easing)) d.push(`\t--kb-ease-${k}: ${bezier(v)};`);
	for (const [k, v] of Object.entries(tokens.motion.distance)) d.push(`\t--kb-distance-${k}: ${v}px;`);
	for (const [k, v] of Object.entries(tokens.size)) d.push(`\t--kb-size-${k}: ${rem(v.px)};`);
	for (const [k, v] of Object.entries(tokens.z)) d.push(`\t--kb-z-${k}: ${v};`);
	out.push(`:root {\n${d.join('\n')}\n}`);
	out.push(
		`@media (prefers-reduced-motion: reduce) {\n\t:root {\n${Object.keys(tokens.motion.distance)
			.map((k) => `\t\t--kb-distance-${k}: 0px;`)
			.join('\n')}\n\t}\n}`
	);
	return out.join('\n\n') + '\n';
}

/** The token block of assets/card/card.css (between the markers). @param {any} tokens */
export function cardBlock(tokens) {
	const colors = resolveColors(tokens);
	const c = tokens.card;
	/** @param {'light'|'dark'} theme @param {string} indent */
	const decls = (theme, indent) =>
		[...Object.entries(c.color).map(([k, ref]) => `${indent}--kb-card-${k}: ${colors[theme][ref].toLowerCase()};`)].join('\n');
	const sizes = Object.entries(c.size)
		.map(([k, v]) => `  --kb-card-size-${k}: ${fluid(v.min, v.max, tokens.type.fluidFromPx, tokens.type.fluidToPx)};`)
		.join('\n');
	return [
		CARD_START,
		`:root {\n  --kb-font: ${fontStack(tokens.font.sans)};\n  --kb-font-serif: ${fontStack(tokens.font.serif)};\n${sizes}\n  --kb-card-leading: ${fmt(c.leading)};\n  --kb-card-ruby-scale: ${fmt(c['ruby-scale'])};\n}`,
		`:root,\n[data-theme="light"] {\n${decls('light', '  ')}\n}`,
		`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${decls('dark', '    ')}\n  }\n}`,
		`[data-theme="dark"] {\n${decls('dark', '  ')}\n}`,
		CARD_END
	].join('\n');
}

/** card.css with its token block replaced. @param {any} tokens @param {string} current */
export function cardCss(tokens, current) {
	const a = current.indexOf(CARD_START);
	const b = current.indexOf(CARD_END);
	if (a < 0 || b < a) throw new Error(`${OUT.cardCss}: token markers missing`);
	return current.slice(0, a) + cardBlock(tokens) + current.slice(b + CARD_END.length);
}

/** Token tables for the /styleguide route. @param {any} tokens */
export function webTs(tokens) {
	const colors = resolveColors(tokens);
	const colorRows = Object.keys(tokens.color).map((k) => ({
		name: k,
		light: colors.light[k],
		dark: colors.dark[k],
		use: tokens.color[k].use ?? ''
	}));
	const roles = Object.entries(tokens.type.roles).map(([name, r]) => ({
		name,
		minRem: r.min,
		maxRem: r.max,
		sp: r.sp,
		lh: r.lh,
		weight: r.weight,
		family: r.family,
		use: r.use ?? ''
	}));
	const data = {
		colors: colorRows,
		contrast: contrastPairs(tokens),
		typeRoles: roles,
		space: Object.entries(tokens.space)
			.map(([name, px]) => ({ name, px }))
			.sort((a, b) => a.px - b.px),
		radius: Object.entries(tokens.radius).map(([name, px]) => ({ name, px })),
		elevation: Object.entries(tokens.elevation).map(([name, e]) => ({ name, dp: e.dp })),
		duration: Object.entries(tokens.motion.duration).map(([name, ms]) => ({ name, ms })),
		easing: Object.entries(tokens.motion.easing).map(([name, b]) => ({ name, css: bezier(b) })),
		size: Object.entries(tokens.size).map(([name, s]) => ({ name, px: s.px, dp: s.dp, use: s.use ?? '' })),
		breakpoint: tokens.breakpoint
	};
	return `// ${BANNER}\n// Token tables for the /styleguide route (values are the resolved hex per theme).\n\nexport const tokens = ${JSON.stringify(data, null, '\t')} as const;\n\nexport type ColorToken = (typeof tokens.colors)[number]['name'];\n`;
}

/** One row per declared fg/bg pair with its ratio in each theme (2 decimals). @param {any} tokens */
function contrastPairs(tokens) {
	/** @type {Map<string, { fg: string, bg: string, kind: string, min: number, light: number, dark: number }>} */
	const rows = new Map();
	for (const r of contrastReport(tokens)) {
		const key = `${r.fg}|${r.bg}`;
		const row = rows.get(key) ?? { fg: r.fg, bg: r.bg, kind: r.kind, min: r.min, light: 0, dark: 0 };
		row[/** @type {'light'|'dark'} */ (r.theme)] = Math.round(r.ratio * 100) / 100;
		rows.set(key, row);
	}
	return [...rows.values()];
}

/** Kotlin `Color(0xAARRGGBB)`. @param {string} hex */
function ktColor(hex) {
	const [r, g, b, a] = parseHex(hex);
	const h = (/** @type {number} */ n) => n.toString(16).padStart(2, '0').toUpperCase();
	return `Color(0x${h(Math.round(a * 255))}${h(r)}${h(g)}${h(b)})`;
}

/** @param {any} tokens */
export function compose(tokens) {
	const colors = resolveColors(tokens);
	const names = Object.keys(tokens.color);
	const t = tokens.type;
	const L = [];
	L.push(`// ${BANNER}`);
	L.push('// Kotobaya design tokens for Compose (docs/DESIGN.md). KotobayaTheme (UI-APP) wires these into MaterialTheme.');
	L.push('@file:Suppress("MagicNumber", "unused")');
	L.push('');
	L.push('package kotobaya.android.ui.theme');
	L.push('');
	for (const i of [
		'androidx.compose.animation.core.CubicBezierEasing',
		'androidx.compose.foundation.shape.RoundedCornerShape',
		'androidx.compose.material3.ColorScheme',
		'androidx.compose.material3.Shapes',
		'androidx.compose.material3.Typography',
		'androidx.compose.material3.darkColorScheme',
		'androidx.compose.material3.lightColorScheme',
		'androidx.compose.runtime.Immutable',
		'androidx.compose.ui.graphics.Color',
		'androidx.compose.ui.text.TextStyle',
		'androidx.compose.ui.text.font.FontFamily',
		'androidx.compose.ui.text.font.FontWeight',
		'androidx.compose.ui.unit.dp',
		'androidx.compose.ui.unit.em',
		'androidx.compose.ui.unit.sp'
	])
		L.push(`import ${i}`);
	L.push('');
	L.push('/** Every semantic colour of one theme (names match the web `--kb-color-*` tokens). */');
	L.push('@Immutable');
	L.push('data class KbColors(');
	for (const n of names) L.push(`    val ${camel(n)}: Color,`);
	L.push(')');
	for (const theme of /** @type {const} */ (['light', 'dark'])) {
		L.push('');
		L.push(`val KbColors${theme === 'light' ? 'Light' : 'Dark'}: KbColors = KbColors(`);
		for (const n of names) L.push(`    ${camel(n)} = ${ktColor(colors[theme][n])},`);
		L.push(')');
	}
	L.push('');
	L.push('/** The Material 3 colour scheme derived from the semantic colours, so stock components fit the palette. */');
	L.push('fun KbColors.toColorScheme(dark: Boolean): ColorScheme =');
	L.push('    if (dark) {');
	L.push('        darkColorScheme(');
	for (const [m, s] of Object.entries(tokens.material3)) L.push(`            ${m} = ${camel(s)},`);
	L.push('        )');
	L.push('    } else {');
	L.push('        lightColorScheme(');
	for (const [m, s] of Object.entries(tokens.material3)) L.push(`            ${m} = ${camel(s)},`);
	L.push('        )');
	L.push('    }');
	L.push('');
	L.push('/** Text styles (sp, so they follow the system font scale). Family-less: [kbTypography] applies the fonts. */');
	L.push('object KbType {');
	for (const [role, r] of Object.entries(t.roles)) {
		L.push(`    /** ${r.use} */`);
		L.push(
			`    val ${camel(role)}: TextStyle = TextStyle(fontSize = ${r.sp}.sp, lineHeight = ${fmt(Math.round(r.sp * r.lh))}.sp, fontWeight = FontWeight(${r.weight}), letterSpacing = ${fmt(r.tracking)}.em)`
		);
	}
	L.push(`    /** Furigana: base size × RUBY_SCALE, never below RUBY_MIN_SP. */`);
	L.push(`    const val RUBY_SCALE: Float = ${fmt(t.ruby.scale)}f`);
	L.push(`    const val RUBY_MIN_SP: Float = ${fmt(t.ruby.minSp)}f`);
	L.push(`    const val RUBY_LINE_HEIGHT: Float = ${fmt(t.ruby.lineHeight)}f`);
	L.push('}');
	L.push('');
	L.push('/** The family of each role (serif roles use the Mincho face). */');
	L.push('private val serifRoles: Set<String> = setOf(' + Object.entries(t.roles).filter(([, r]) => r.family === 'serif').map(([n]) => `"${camel(n)}"`).join(', ') + ')');
	L.push('');
	L.push('/** Material 3 typography from [KbType]. Pass the bundled Noto Sans JP / Noto Serif JP families (UI-APP). */');
	L.push('fun kbTypography(sans: FontFamily = FontFamily.Default, serif: FontFamily = FontFamily.Serif): Typography {');
	L.push('    fun f(role: String, s: TextStyle): TextStyle = s.copy(fontFamily = if (role in serifRoles) serif else sans)');
	L.push('    return Typography(');
	for (const [m, role] of Object.entries(t.material3)) L.push(`        ${m} = f("${camel(role)}", KbType.${camel(role)}),`);
	L.push('    )');
	L.push('}');
	L.push('');
	L.push('object KbSpace {');
	for (const [k, v] of Object.entries(tokens.space).sort((a, b) => a[1] - b[1])) L.push(`    val s${k.replace('-', '_')} = ${v}.dp`);
	L.push('}');
	L.push('');
	L.push('object KbRadius {');
	for (const [k, v] of Object.entries(tokens.radius)) L.push(`    val ${camel(k)} = ${v}.dp`);
	L.push('}');
	L.push('');
	const r = tokens.radius;
	L.push('val KbShapes: Shapes = Shapes(');
	L.push(`    extraSmall = RoundedCornerShape(${r.xs}.dp),`);
	L.push(`    small = RoundedCornerShape(${r.sm}.dp),`);
	L.push(`    medium = RoundedCornerShape(${r.md}.dp),`);
	L.push(`    large = RoundedCornerShape(${r.lg}.dp),`);
	L.push(`    extraLarge = RoundedCornerShape(${r.xl}.dp),`);
	L.push(')');
	L.push('');
	L.push('object KbElevation {');
	for (const [k, v] of Object.entries(tokens.elevation)) L.push(`    val level${k} = ${v.dp}.dp`);
	L.push('}');
	L.push('');
	L.push('/** Durations in ms (all under 250). Under reduced motion (animator scale 0) use fades only, no movement. */');
	L.push('object KbMotion {');
	for (const [k, v] of Object.entries(tokens.motion.duration)) L.push(`    const val ${k.toUpperCase()}: Int = ${v}`);
	for (const [k, v] of Object.entries(tokens.motion.easing))
		L.push(`    val ${camel(k)}: CubicBezierEasing = CubicBezierEasing(${v.map((/** @type {number} */ n) => `${fmt(n)}f`).join(', ')})`);
	for (const [k, v] of Object.entries(tokens.motion.distance)) L.push(`    val distance${k[0].toUpperCase() + k.slice(1)} = ${v}.dp`);
	L.push('}');
	L.push('');
	L.push('object KbSize {');
	for (const [k, v] of Object.entries(tokens.size)) L.push(`    val ${camel(k)} = ${v.dp}.dp`);
	L.push('}');
	L.push('');
	L.push('/** Window width breakpoints (dp, min-width); same values as the web breakpoints in px. */');
	L.push('object KbBreakpoint {');
	for (const [k, v] of Object.entries(tokens.breakpoint)) L.push(`    val ${camel(k)} = ${v}.dp`);
	L.push('}');
	return L.join('\n') + '\n';
}

/** Every output path (repo-relative) → the content the token file generates. */
export function generateAll(tokens = loadTokens()) {
	return {
		[OUT.webCss]: webCss(tokens),
		[OUT.webTs]: webTs(tokens),
		[OUT.cardCss]: cardCss(tokens, read(OUT.cardCss)),
		[OUT.compose]: compose(tokens)
	};
}

/** Output paths whose file on disk differs from the generated content. */
export function drift(tokens = loadTokens()) {
	const stale = [];
	for (const [p, content] of Object.entries(generateAll(tokens))) {
		let disk = null;
		try {
			disk = read(p);
		} catch {
			disk = null;
		}
		if (disk !== content) stale.push(p);
	}
	return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	if (process.argv.includes('--check')) {
		const stale = drift();
		if (stale.length) {
			console.error(`tokens: out of date (run \`make tokens\`): ${stale.join(', ')}`);
			process.exit(1);
		}
		console.log('tokens: up to date');
	} else {
		for (const [p, content] of Object.entries(generateAll())) {
			mkdirSync(dirname(join(ROOT, p)), { recursive: true });
			writeFileSync(join(ROOT, p), content);
			console.log(`wrote ${relative(process.cwd(), join(ROOT, p))}`);
		}
	}
}
