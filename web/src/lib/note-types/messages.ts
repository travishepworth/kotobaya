export type NoteTypeMessageKey = keyof typeof en;

export function tn(key: NoteTypeMessageKey, params?: Record<string, string | number>): string {
	let s: string = en[key];
	if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}
