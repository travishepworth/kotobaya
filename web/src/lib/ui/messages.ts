export type UiMessageKey = keyof typeof en;

/** Translates a design-system string; `{name}` placeholders are filled from params. */
export function ut(key: UiMessageKey, params?: Record<string, string | number>): string {
	let s: string = en[key];
	if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
	return s;
}
